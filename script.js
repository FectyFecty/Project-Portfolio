document.querySelectorAll('a[href^="#"]:not(#copyEmail)').forEach((link) => {
  link.addEventListener("click", (event) => {
    const targetId = link.getAttribute("href");

    if (!targetId || targetId === "#") {
      return;
    }

    const target = document.querySelector(targetId);

    if (!target) {
      return;
    }

    event.preventDefault();
    target.scrollIntoView({ behavior: "smooth", block: "start" });

    const navCollapse = document.querySelector(".navbar-collapse.show");
    if (navCollapse && window.bootstrap) {
      window.bootstrap.Collapse.getOrCreateInstance(navCollapse).hide();
    }
  });
});

const sections = [...document.querySelectorAll("main section[id], footer[id]")];
const navLinks = [...document.querySelectorAll(".nav-link[href^='#']")];

if (sections.length && navLinks.length) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) {
          return;
        }

        navLinks.forEach((link) => {
          link.classList.toggle(
            "active",
            link.getAttribute("href") === `#${entry.target.id}`,
          );
        });
      });
    },
    { rootMargin: "-38% 0px -56% 0px" },
  );

  sections.forEach((section) => observer.observe(section));
}

function renderCategoryPage() {
  const title = document.querySelector("#categoryTitle");
  const description = document.querySelector("#categoryDescription");
  const showcase = document.querySelector("#categoryShowcase");
  const previousButton = document.querySelector("#previousProject");
  const nextButton = document.querySelector("#nextProject");

  if (!title || !description || !showcase || !previousButton || !nextButton) {
    return;
  }

  const params = new URLSearchParams(window.location.search);
  const selectedCategory = params.get("category") || "ui-ux";
  const content = categoryContent[selectedCategory] || categoryContent["ui-ux"];
  activeCategoryKey = categoryContent[selectedCategory]
    ? selectedCategory
    : "ui-ux";
  activeProjectIndex = 0;

  document.title = `${content.title} | Project Portfolio`;
  title.textContent = content.title;
  description.textContent = content.description;

  previousButton.addEventListener("click", () => moveProject(-1));
  nextButton.addEventListener("click", () => moveProject(1));
  document.addEventListener("keydown", (event) => {
    if (event.key === "ArrowLeft") {
      moveProject(-1);
    }

    if (event.key === "ArrowRight") {
      moveProject(1);
    }
  });

  renderProject();
}

function moveProject(direction) {
  const projects = categoryContent[activeCategoryKey].projects;
  activeProjectIndex =
    (activeProjectIndex + direction + projects.length) % projects.length;

  const showcase = document.querySelector("#categoryShowcase");
  if (!showcase) {
    renderProject();
    return;
  }

  showcase.classList.add("is-switching");
  window.setTimeout(() => {
    renderProject();
    showcase.classList.remove("is-switching");
  }, 170);
}

function renderProject() {
  const content = categoryContent[activeCategoryKey];
  const project = content.projects[activeProjectIndex];
  const imageFrame = document.querySelector("#projectImageFrame");
  const projectTitle = document.querySelector("#projectTitle");
  const projectCategory = document.querySelector("#projectCategory");
  const projectDescription = document.querySelector("#projectDescription");
  const projectMeta = document.querySelector("#projectMeta");
  const projectLinksWrap = document.querySelector("#projectLinksWrap");
  const projectLinks = document.querySelector("#projectLinks");
  const projectCounter = document.querySelector("#projectCounter");

  if (
    !imageFrame ||
    !projectTitle ||
    !projectCategory ||
    !projectDescription ||
    !projectMeta ||
    !projectLinksWrap ||
    !projectLinks ||
    !projectCounter
  ) {
    return;
  }

  const visualLabel = `${project.title} project preview`;
  imageFrame.innerHTML = project.image
    ? `<img src="${project.image}" alt="${visualLabel}" />`
    : `<div class="project-visual-fallback" role="img" aria-label="${visualLabel}"></div>`;

  projectTitle.textContent = project.title;
  projectCategory.textContent = content.title;
  projectDescription.textContent = project.description;

  projectMeta.innerHTML = project.metadata
    .slice(0, 4)
    .map(
      ({ label, value }) => `
        <div>
          <dt>${label}</dt>
          <dd>${value}</dd>
        </div>
      `,
    )
    .join("");

  const actions = project.actions
    .filter(({ optional, url }) => url || !optional)
    .slice(0, 1);
  projectLinksWrap.hidden = !actions.length;
  projectLinks.innerHTML = actions
    .map(
      ({ type, title, url }) => `
        <a class="project-action-card" href="${url || actionFallbackUrls[type] || "#"}" target="_blank" rel="noreferrer" aria-label="${title}">
          <span class="action-icon">
            <i class="bi ${actionIcons[type] || "bi-arrow-up-right"}" aria-hidden="true"></i>
          </span>
          <span class="action-title">${title}</span>
          <span class="action-open"><i class="bi bi-arrow-up-right" aria-hidden="true"></i></span>
        </a>
      `,
    )
    .join("");

  projectCounter.textContent = `${activeProjectIndex + 1} / ${
    content.projects.length
  }`;
}

renderCategoryPage();

